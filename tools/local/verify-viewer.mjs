import { chromium, expect } from '../../frontend/node_modules/@playwright/test/index.mjs';
const browser = await chromium.launch({headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader']});
const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('dialog', async dialog => {errors.push('Dialog: ' + dialog.message()); await dialog.dismiss();});
await page.goto('http://127.0.0.1:8666/');
await page.waitForFunction(() => window.g?.MODEL3D?.anim?.frameCount > 1, {timeout: 60000});
await expect(page.locator('#loading-screen')).toHaveCount(0);
await page.waitForFunction(() => window.g.MODEL3D.skeletonHelper.visible);
await expect(page.locator('#temporalLabelSegments')).toBeVisible();
const first = await page.evaluate(() => {
    const g = window.g;
    g.PLAYING = false;
    g.FRAME = 0;
    return {name: g.FILENAME, frames: g.MODEL3D.anim.frameCount, fps: g.MODEL3D.anim.fps};
});
await page.waitForTimeout(200);
const before = await page.evaluate(() => [...window.g.MODEL3D.skeletonHelper.geometry.attributes.position.array]);
await page.evaluate(() => {window.g.FRAME = Math.min(100, window.g.MODEL3D.anim.maxFrame);});
await page.waitForTimeout(250);
const after = await page.evaluate(() => [...window.g.MODEL3D.skeletonHelper.geometry.attributes.position.array]);
if (!before.some((v, i) => Math.abs(v - after[i]) > 0.0001)) throw new Error('Skeleton did not move between frames');
await page.locator('#tab-search-input').fill(first.name);
await page.locator('#tab-search-input').press('Enter');
await expect(page.locator('#browser-table tbody tr').first()).toContainText(first.name);
await page.locator('#tab-search-input').fill('');
await page.locator('#tab-search-input').press('Enter');
await page.locator('#tab-random').click();
await page.waitForFunction(name => window.g.FILENAME !== name, first.name);
const randomName = await page.evaluate(() => window.g.FILENAME);
await page.locator('[data-model="g1"]').click();
await page.waitForFunction(name => window.g.CURRENT_MODEL === 'g1' && typeof window.g.MODEL3D?.anim?.getFrameData === 'function' && window.g.FILENAME === name, randomName);
await page.locator('[data-model="soma"]').click();
await page.waitForFunction(name => window.g.CURRENT_MODEL === 'soma' && window.g.MODEL3D?.anim?.anim?.skeleton && window.g.FILENAME === name, randomName);
await page.waitForTimeout(300);
await page.screenshot({path: '/home/imlab/Desktop/Bill/bones-tools/viewer-verified.png', fullPage: true});
if (errors.length) throw new Error(JSON.stringify(errors));
console.log(JSON.stringify({result: 'PASS', ...first, skeletonAnimated: true, modelSwitching: true, temporalSegments: await page.locator('#temporalLabelSegments > div').count(), randomMotion: await page.evaluate(() => window.g.FILENAME), errors}));
await browser.close();
