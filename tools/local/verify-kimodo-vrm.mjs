import {chromium, expect} from '../../frontend/node_modules/@playwright/test/index.mjs';
import {writeFile} from 'node:fs/promises';

const browser = await chromium.connectOverCDP('http://127.0.0.1:9334');
const page = browser.contexts()[0].pages().find(p => p.url().includes(':7860')) ?? await browser.contexts()[0].newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const cdp = await page.context().newCDPSession(page);
await cdp.send('Network.enable'); await cdp.send('Network.setCacheDisabled', {cacheDisabled: true});
await page.goto('http://127.0.0.1:7860/'); await page.bringToFront();
await page.locator('#kimodo-vrm-preview').waitFor({timeout: 60000});
const welcome = page.getByRole('button', {name: "Got it (don't remind me again)"});
if (await welcome.isVisible()) await welcome.click();
const frame = page.frame({url: /kimodo-preview/});
await frame.waitForFunction(() => window.kimodoPreview?.models === 1, null, {timeout: 60000});
await expect(page.getByLabel('VRoid Preview')).toBeChecked();
await page.getByRole('button', {name: 'Generate', exact: true}).click();
await expect(page.getByText('Motion generation finished!', {exact: true})).toBeVisible({timeout: 180000});
await frame.waitForFunction(() => window.kimodoPreview.inspect()[0]?.frames === 180, null, {timeout: 30000});
const initial = await frame.evaluate(() => window.kimodoPreview.inspect()[0]);
await frame.locator('#preview').click();
await frame.locator('#preview').press('Space');
await frame.waitForFunction(() => window.kimodoPreview.frame >= 30, null, {timeout: 10000});
await frame.locator('#preview').press('Space');
await page.waitForTimeout(200);
const stopped = await frame.evaluate(() => ({frame: window.kimodoPreview.frame, pose: window.kimodoPreview.inspect()[0]}));
await page.waitForTimeout(200);
if (await frame.evaluate(() => window.kimodoPreview.frame) !== stopped.frame) throw new Error('Pause did not stop playback');
if (!initial.rotations.some((v, i) => Math.abs(v - stopped.pose.rotations[i]) > 1e-4)) throw new Error('Generated motion did not change VRoid pose');
if (!stopped.pose.rotations.every(Number.isFinite) || stopped.pose.mappedBones !== 54) throw new Error('Invalid VRoid pose');
await frame.locator('#preview').press('ArrowRight');
await frame.waitForFunction(f => window.kimodoPreview.frame === f + 1, stopped.frame);
await page.getByLabel('VRoid Preview').uncheck();
await expect(page.locator('#kimodo-vrm-preview')).toBeHidden();
await page.getByLabel('VRoid Preview').check();
await expect(page.locator('#kimodo-vrm-preview')).toBeVisible();

await page.getByText('Constraints', {exact: true}).first().click();
await page.getByRole('button', {name: 'Enter Editing Mode', exact: true}).click();
await expect(page.locator('#kimodo-vrm-preview')).toBeHidden();
await page.getByRole('button', {name: 'Exit Editing Mode', exact: true}).click();
await expect(page.locator('#kimodo-vrm-preview')).toBeVisible();
await page.getByText('Constraints', {exact: true}).first().click();
await frame.waitForFunction(() => window.kimodoPreview.errors.length === 0);
await frame.locator('#preview').click();
await frame.locator('#preview').press('Space');
const before = await frame.evaluate(() => window.kimodoPreview.frame);
await page.waitForTimeout(350);
const after = await frame.evaluate(() => window.kimodoPreview.frame);
if (before === after || errors.length) throw new Error(JSON.stringify({before, after, errors}));
await page.screenshot({path: '/home/imlab/Desktop/Bill/bones-example/kimodo-vrm-generated.png', fullPage: true});
const result = {url: page.url(), prompt: 'A person walks forward.', model: 'Kimodo-SOMA-RP-v1.1', generatedFrames: 180, fps: 30, mappedBones: 54, generatedOnGpu: true, automaticPreview: true, keyboardPlayback: true, frameStep: true, editingViewSwitch: true, playing: true, errors};
await writeFile('/home/imlab/Desktop/Bill/bones-example/kimodo-vrm-generation-verification.json', JSON.stringify(result, null, 2));
console.log('PASS', result);
process.exit(0);
